"""Regenerate apps/road_sight/services.js and the signals block of app.json from the owner's interface catalog.

Only interface, event and field NAMES are written (they are needed to subscribe). No type definitions are copied.
Usage: python tools/gen_services.py <catalog.json>   (or set ROAD_SIGHT_CATALOG)
"""
from pathlib import Path
import json
import os
import sys

ROOT = Path(__file__).resolve().parents[1]
APP = ROOT / 'apps' / 'road_sight'
SOURCE = sys.argv[1] if len(sys.argv) > 1 else os.environ.get('ROAD_SIGHT_CATALOG')
if not SOURCE:
    raise SystemExit('Give the path of your own interface catalog (argument or ROAD_SIGHT_CATALOG)')
CATALOG = Path(SOURCE)

# service ids the head unit's own configuration rate-limits (so they do arrive)
RATE_LIMITED = {0xD540, 0xD110}
# service ids found in the body controller gateway's table of SOME/IP events (offline analysis of one table family)
IN_GATEWAY_TABLE = {0xD537, 0xD534, 0xD536, 0x3540, 0x3539}
# what each group shows on the page
GROUPS = [
    ('Lanes', ['de.bmw.environmentalmodel.LaneBoundariesLegacy2', 'de.bmw.environmentalmodel.LaneBoundariesLegacy',
               'de.bmw.sensors.road.SemanticLaneDescription', 'de.bmw.environmentalmodel.LaneBoundaries',
               'de.bmw.environmentalmodel.Lanes', 'de.bmw.environmentalmodel.LaneChangeInformation',
               'de.bmw.environmentalmodel.Road', 'de.bmw.environmentalmodel.LanePreciseLocalization']),
    ('Signs', ['de.bmw.environmentalmodel.SignRecognitionFrontCameraLegacy', 'de.bmw.environmentalmodel.SignRecognitionFrontCamera',
               'de.bmw.dass.TrafficSignRecognition']),
    ('Lights', ['de.bmw.environmentalmodel.TrafficLightRecognitionFrontCameraLegacy', 'de.bmw.sensors.objects.RecogFrontCameraLightDetection']),
    ('Objects', ['de.bmw.environmentalmodel.DAADataServer', 'de.bmw.environmentalmodel.ObjectRecognitionFrontCamera',
                 'de.bmw.environmentalmodel.ObjectRecognitionFrontCamera2', 'de.bmw.environmentalmodel.FusedSensorDetectionData',
                 'de.bmw.sensors.objects.RecogFrontCameraObjectlist', 'de.bmw.dass.pad.communication.ObjectListSuAAR',
                 'de.bmw.dass.GapVehicleAhead', 'de.bmw.dass.ParkDistanceInformation']),
    ('Warnings', ['de.bmw.dass.driverassistanceapplications.LateralCollisionAvoidance',
                  'de.bmw.dass.driverassistanceapplications.AssistedDrivingViewLateralCollisionAvoidance',
                  'de.bmw.dass.AssistedDrivingViewFunctionInput',
                  'de.bmw.dass.pad.communication.AssistedDrivingViewLateralFunctionInput']),
    ('Conditions', ['de.bmw.environmentalmodel.environmentalconditions.Weather',
                    'de.bmw.environmentalmodel.environmentalconditions.BlockageAndWeatherFrontCameraMain',
                    'de.bmw.environmentalmodel.EgoMotionLegacy', 'de.bmw.environmentalmodel.roadforesight.AutonomousDrivingOffboardRoadApproval']),
]


def main():
    catalog = json.loads(CATALOG.read_text(encoding='utf-8'))
    interfaces, instances = catalog['interfaces'], catalog['instanceIDs']
    services, signals, skipped = [], {}, []
    for group, names in GROUPS:
        for name in names:
            spec = interfaces.get(name)
            if not spec:
                skipped.append(name)
                continue
            events = sorted(spec.get('events', {}))
            fields = sorted(f for f, x in spec.get('fields', {}).items() if 'notifier' in x)
            if not events and not fields:
                skipped.append(name)
                continue
            inst = instances.get(name, {})
            instance = '1' if '1' in inst or not inst else sorted(inst)[0]
            sid = spec['serviceId']
            evidence = 'A' if sid in RATE_LIMITED else 'B' if sid in IN_GATEWAY_TABLE else 'C'
            services.append({'iface': name, 'name': name.split('.')[-1], 'group': group, 'id': sid, 'instance': instance,
                             'evidence': evidence, 'events': events, 'fields': fields})
            block = {'_instances': instance, '_optional': group + ': ' + name.split('.')[-1]}
            for field in fields:
                block[field] = 's'
            if events:
                block['_broadcasts'] = events
            signals[name] = block
    lines = ["'use strict';",
             '// Generated by tools/gen_services.py from the owner\'s interface catalog. Names only; do not edit by hand.',
             '// evidence: A = the head unit rate-limits it (it arrives), B = listed in the BDC gateway table, C = defined only.',
             'module.exports = ' + json.dumps(services, indent=1) + ';', '']
    (APP / 'services.js').write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    manifest_path = APP / 'app.json'
    manifest = json.loads(manifest_path.read_text(encoding='utf-8'))
    manifest['signals'] = signals
    manifest_path.write_text(json.dumps(manifest, indent=1) + '\n', encoding='utf-8', newline='\n')
    total = sum(len(s['events']) + len(s['fields']) for s in services)
    print('services', len(services), 'subscriptions', total, 'not in catalog or empty:', skipped)


if __name__ == '__main__':
    main()
